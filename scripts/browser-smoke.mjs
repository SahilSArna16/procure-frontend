// Run with PLAYWRIGHT_MODULE=/path/to/playwright/index.mjs node scripts/browser-smoke.mjs.
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
await mkdir('/tmp/procurement-artifacts', { recursive: true })
await page.goto(process.env.APP_URL || 'http://127.0.0.1:5174')
await page.getByRole('button', { name: 'Load Sample Dataset', exact: true }).first().click()
await page.getByText('SAMPLE DATA', { exact: true }).waitFor()
assert.equal(await page.locator('.comparison-table tbody tr').count(), 30)
assert.equal(await page.locator('.supplier-header').count(), 5)
await page.screenshot({ path: '/tmp/procurement-artifacts/desktop.png', fullPage: true })
await page.getByLabel('Search SKUs').fill('SKU-015')
assert.equal(await page.locator('.comparison-table tbody tr').count(), 1)
await page.getByLabel('Search SKUs').fill('')
await page.getByLabel('QA-approved only', { exact: true }).check()
assert.equal(await page.locator('.supplier-header').count(), 3)
await page.getByLabel('QA-approved only', { exact: true }).uncheck()
await page.locator('.supplier-header').first().click()
await page.getByRole('dialog').waitFor()
assert.equal(await page.getByLabel('Buyer QA decision').inputValue(), 'passed')
await page.getByLabel('Close quote review').click()
await page.getByRole('tab', { name: 'Award scenarios' }).click()
await page.getByRole('button', { name: 'At most 2 suppliers' }).click()
await page.locator('.conversation .buyer-question').waitFor()
assert.match(await page.locator('.conversation .buyer-question').innerText(), /Split the award between at most two approved suppliers/)
await page.locator('.conversation .scenario-result').waitFor()
assert.equal(await page.locator('.conversation .award-table tbody tr').count(), 2)
await page.getByRole('tab', { name: /Master SKUs/ }).click()
await page.getByRole('button', { name: 'Edit specifications' }).click()
await page.getByLabel('Weight SKU-001', { exact: true }).fill('0.3')
await page.getByRole('button', { name: 'Save master', exact: true }).click()
await page.getByText('Saved. Prices and award recommendations have been recalculated.').waitFor()
await page.reload()
await page.getByText('SAMPLE DATA', { exact: true }).waitFor()
await page.getByRole('tab', { name: /Master SKUs/ }).click()
assert.match(await page.locator('.master-table tbody tr').first().innerText(), /0\.3/)
const exportResponse = await page.request.get((process.env.APP_URL || 'http://127.0.0.1:5174') + '/api/workspaces/' + await page.evaluate(() => localStorage.getItem('procure.workspace')) + '/export')
assert.equal(exportResponse.status(), 200)
assert.match(await exportResponse.text(), /Award total INR/)
await page.getByRole('tab', { name: 'Price comparison' }).click()
await page.setViewportSize({ width: 390, height: 844 })
await page.screenshot({ path: '/tmp/procurement-artifacts/mobile.png', fullPage: true })
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
assert.equal(overflow, false, 'Mobile page must not overflow horizontally')
assert.deepEqual(errors, [])
await browser.close()
console.log('PASS browser: demo, comparison, search, QA filter, review dialog, scenario, master save, persistence, export, responsive layout, no console errors')
