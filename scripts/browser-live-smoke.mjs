// Opt-in: uses Sarvam credits and persists a synthetic comparison in Neon.
import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173')
await page.getByLabel('Import master SKU CSV').setInputFiles({ name: 'master.csv', mimeType: 'text/csv', buffer: Buffer.from('sku_id,description,factory,ply,weight_kg,quantity\nSKU-001,3-ply carton,Pune,3,0.5,10\nSKU-002,5-ply carton,Chennai,5,0.25,20\n') })
await page.getByText('Master imported. This is a new comparison; your previous comparison has been retained.').waitFor({ timeout: 30000 })
await page.getByLabel('Upload supplier quotes').setInputFiles({ name: 'acme-quote.txt', mimeType: 'text/plain', buffer: Buffer.from('Supplier: Acme Boxes\nPayment terms: Net 60. Currency: INR.\nSKU-001: INR 10 per box.\nSKU-002: INR 42 per kg.\nFreight included: no fixed or per-box freight charge. No discounts. GST 18% extra.\n') })
console.log('Waiting for live Sarvam extraction through the browser…')
await page.getByText('1 quotation(s) added. Successful files are saved independently. Review supplier terms and QA before awarding.').waitFor({ timeout: 240000 })
assert.equal(await page.locator('.supplier-card').count(), 1)
await page.locator('.supplier-card').click()
assert.equal(await page.getByLabel('Buyer QA decision').inputValue(), 'pending')
await page.getByLabel('Buyer QA decision').selectOption('passed')
await page.getByRole('button', { name: 'Confirm freight included for all items' }).click()
await page.getByLabel('Needs review SKU-001', { exact: true }).uncheck()
await page.getByLabel('Needs review SKU-002', { exact: true }).uncheck()
await page.getByText('I verified the rates and all commercial terms against the original quote.').check()
await page.getByRole('button', { name: 'Save & recalculate' }).click()
await page.getByText('Saved. Prices and award recommendations have been recalculated.').waitFor()
await page.getByRole('tab', { name: 'Price comparison' }).click()
assert.equal(await page.locator('.comparison-table tbody tr').count(), 2)
assert.match(await page.locator('.comparison-table tbody tr').nth(1).innerText(), /₹10\.50/)
await page.getByLabel('Ask a procurement scenario').fill('Double all order quantities and show the best split award among QA-approved suppliers, excluding GST.')
await page.getByRole('button', { name: 'Calculate scenario' }).click()
await page.locator('.conversation .result-total').waitFor({ timeout: 180000 })
assert.match(await page.locator('.conversation .result-total').innerText(), /620\.00/)
await page.screenshot({ path: '/tmp/procurement-artifacts/live-scenario.png', fullPage: true })
await page.reload()
await page.locator('.comparison-table tbody tr').nth(1).waitFor()
assert.match(await page.locator('.comparison-table tbody tr').nth(1).innerText(), /₹10\.50/)
assert.deepEqual(errors, [])
await browser.close()
console.log('PASS live browser flow: CSV master → TXT upload → Sarvam extraction → buyer QA/terms review → kg normalization → exact natural-language 2× award ₹620.00 → Neon persistence')
